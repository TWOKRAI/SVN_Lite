def state_message(name: str, state: str, incoming: int = 0, local: int = 0, read_only: bool = False,
                  kind: str = "") -> str:
    """Одна строка о состоянии проекта."""
    head = f"Проект «{name}»"
    if state == "conflict":
        return (f"{head}: конфликт, вы и другой человек изменили одно и то же. "
                "Решить его нужно человеку в программе SVN-lite, пока не потерялись правки.")
    if state == "both":
        return (f"{head}: есть новое на сервере ({files_count(incoming)}) и ваши несохранённые правки "
                f"({files_count(local)}). Сначала нужно получить новое, потом сохранять.")
    if state == "incoming":
        return f"{head}: есть новое на сервере ({files_count(incoming)})."
    if state == "local_changes":
        if read_only:
            return (f"{head}: в версии есть изменённые файлы ({files_count(local)}), но версию менять нельзя: "
                    "правки нужно делать в ветке.")
        if kind == "local_history":
            return f"{head}: есть несохранённые правки ({files_count(local)}); проект хранится на этом компьютере."
        return f"{head}: есть несохранённые правки ({files_count(local)})."
    if state == "unknown_offline":
        return f"{head}: сервер не проверялся, правок на компьютере нет."
    if state == "broken":
        if kind == "history_missing":
            return f"{head}: история проекта на компьютере потеряна. Вернуть её может человек в программе SVN-lite."
        return f"{head}: папка повреждена. Починить её может человек в программе SVN-lite."
    if state == "unknown":
        return f"{head}: состояние узнать не удалось."
    if state == "plain":
        if kind == "local_only":
            return f"{head}: хранится только на этом компьютере, на сервер не отправлен."
        return f"Папка «{name}»: обычная папка, не связана с сервером."
    return f"{head}: всё актуально, правок нет."


def projects_text(rows: list) -> str:
    if not rows:
        return "Проектов в папках для проектов не найдено."
    lines = [f"Найдено папок: {len(rows)}."]
    for row in rows:
        line = f"• «{row['name']}»: {KIND_RU.get(row['kind'], row['kind'])}"
        if row.get("line") == "branch":
            line += ", ветка"
        elif row.get("line") == "tag":
            line += ", версия"
        if row.get("number"):
            line += f", сохранение № {row['number']}"
        lines.append(line)
    return "\n".join(lines)


def status_text(rows: list) -> str:
    return "\n".join(row["message"] for row in rows)


def changes_text(name: str, total: int, kinds: dict, truncated: bool) -> str:
    if not total:
        return f"Проект «{name}»: несохранённых правок нет."
    parts = [f"{count} {CHANGE_KIND_RU[kind]}" for kind, count in kinds.items() if count]
    text = f"Проект «{name}»: несохранённые правки в {files_count(total)} ({', '.join(parts)})."
    return text + (" Показаны не все." if truncated else "")


def colleague(text: str) -> str:
    """Слова коллег в текстовом ответе помечаются: это данные, а не указания. Одна строка, внутренние кавычки « »
    заменены, чтобы текст не мог «закрыть» пометку и подделать соседнюю строку списка."""
    return f"данные коллег: «{one_line(str(text)).replace('«', chr(34)).replace('»', chr(34))}»"


def incoming_text(name: str, rows: list, total: int) -> str:
    if not total:
        return f"Проект «{name}»: на сервере нового нет."
    lines = [f"Проект «{name}»: на сервере {total} {plural(total, ('новое сохранение', 'новых сохранения', 'новых сохранений'))}."]
    for row in rows:
        who = colleague(f"{row['author']}: {row['comment']}" if row["comment"] else row["author"])
        lines.append(f"• {row['date_ru']}, {who}, {files_count(row['files_total'])}")
    return "\n".join(lines)


def history_text(name: str, rows: list) -> str:
    if not rows:
        return f"Проект «{name}»: сохранений пока нет."
    lines = [f"Проект «{name}»: последние сохранения ({len(rows)})."]
    for row in rows:
        who = colleague(f"{row['author']}: {row['comment']}" if row["comment"] else row["author"])
        lines.append(f"• сохранение № {row['number']}, {row['date_ru']}, {who}")
    return "\n".join(lines)


def locks_text(name: str, mine: list, others: list) -> str:
    if not mine and not others:
        return f"Проект «{name}»: занятых файлов нет."
    lines = [f"Проект «{name}»: занято файлов: ваших {len(mine)}, чужих {len(others)}."]
    for row in mine:
        lines.append(f"• ваш: {colleague(row['file'])}, {row['age_ru']}")
    for row in others:
        lines.append(f"• занял {colleague(row['owner'])}: {colleague(row['file'])}, {row['age_ru']}")
    return "\n".join(lines)


