def server_projects_text(path: str, rows: list, truncated: bool) -> str:
    where = f"«{path}»" if path else "на сервере"
    if not rows:
        return f"В {where} вложенных папок нет." if path else "На сервере нет доступных папок."
    lines = [f"В {where} папок: {len(rows)}." + (" Показаны не все." if truncated else "")]
    for row in rows:
        mark = "проект" if row["is_project"] else "папка"
        lines.append(f"• {mark}: {colleague(row['path'])}")
    return "\n".join(lines)


